#!/usr/bin/env python3
"""Generate the Windows-936 double-byte lookup table used by encoding.cpp."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rows = []
for lead in range(0x81, 0xFF):
    values = []
    for trail in [*range(0x40, 0x7F), *range(0x80, 0xFF)]:
        try:
            decoded = bytes((lead, trail)).decode("gbk")
            value = ord(decoded) if len(decoded) == 1 else 0
        except UnicodeDecodeError:
            value = 0
        values.append(value)
    rows.append("    {" + ", ".join(f"0x{x:04X}" for x in values) + "},")
(ROOT / "src/text/cp936_table.inc").write_text(
    "// Generated by tools/gen_cp936.py from Python's Windows-936-compatible GBK codec.\n"
    "constexpr char32_t kCp936Table[126][190] = {\n" + "\n".join(rows) + "\n};\n",
    encoding="utf-8",
)
